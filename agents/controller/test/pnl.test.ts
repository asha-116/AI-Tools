import { describe, expect, it } from 'vitest';
import type { CostRow, RefundRow, SaleRow } from '../src/ledger.js';
import {
  computeWeeklyPnl,
  PNL_END,
  PNL_START,
  renderWeeklyPnl,
  upsertPnlSection,
} from '../src/pnl.js';

const sale = (
  paymentId: string,
  productSlug: string,
  amountPaise: number,
  feePaise: number,
  tax: number,
  date = '2026-10-05',
): SaleRow => ({
  date,
  paymentId,
  orderId: '',
  productSlug,
  amountPaise,
  feePaise,
  taxOnFeePaise: tax,
  status: 'captured',
});

const SALES = [
  sale('pay_A1', 'lead-tracker', 19900, 398, 72),
  sale('pay_B2', 'commission-ledger', 29900, 598, 108, '2026-10-11'),
  sale('pay_C3', 'bundle', 39900, 798, 144),
  sale('pay_E5', 'unmatched', 50000, 1000, 180),
  sale('pay_NEXT', 'lead-tracker', 19900, 398, 72, '2026-10-12'),
  sale('pay_PREV', 'lead-tracker', 19900, 398, 72, '2026-10-04'),
];
const refund = (
  refundId: string,
  paymentId: string,
  amountPaise: number,
  date: string,
): RefundRow => ({
  date,
  refundId,
  paymentId,
  amountPaise,
  reasonCode: '',
  approvedBy: '',
});
const REFUNDS = [
  refund('rfnd_R1', 'pay_C3', 39900, '2026-10-05'),
  refund('rfnd_R2', 'pay_NEXT', 19900, '2026-10-12'),
];
const COSTS: CostRow[] = [
  { date: '2026-10-06', service: 'domain', amountPaise: 99900, note: 'renewal | 1 yr' },
  { date: '2026-10-01', service: 'other', amountPaise: 100, note: '' },
];

describe('weekly P&L', () => {
  // Hand computation for 2026-W41 (Mon 5 – Sun 11 Oct 2026, IST):
  //   bundle            39900 − 798 − 144 − 39900 refund = −942
  //   commission-ledger 29900 − 598 − 108               = 29194
  //   lead-tracker      19900 − 398 −  72               = 19430
  //   unmatched         50000 − 1000 − 180              = 48820
  //   total             139700 − 2794 − 504 − 39900     = 96502; minus costs 99900 = −3398
  const pnl = computeWeeklyPnl({ week: '2026-W41', sales: SALES, refunds: REFUNDS, costs: COSTS });

  it('computes totals and per-product lines', () => {
    expect(pnl.total).toEqual({
      product: 'Total',
      count: 4,
      grossPaise: 139700,
      feesPaise: 2794,
      taxOnFeesPaise: 504,
      refundsPaise: 39900,
      netPaise: 96502,
    });
    expect(pnl.byProduct.map((l) => [l.product, l.netPaise])).toEqual([
      ['bundle', -942],
      ['commission-ledger', 29194],
      ['lead-tracker', 19430],
      ['unmatched', 48820],
    ]);
    expect(pnl.costsPaise).toBe(99900);
    expect(pnl.netAfterCostsPaise).toBe(-3398);
  });

  it('renders Indian-formatted markdown', () => {
    expect(renderWeeklyPnl(pnl)).toBe(
      [
        '## Weekly P&L — 2026-W41',
        '',
        '2026-10-05 to 2026-10-11 (Monday–Sunday, IST). Generated by the Controller from',
        '`company/ledger/*.csv`. Arithmetic only — not tax advice; GST treatment is for a CA to confirm.',
        '',
        '| Line | Amount |',
        '| --- | ---: |',
        '| Gross sales (4 payments) | ₹1,397.00 |',
        '| Razorpay fees (excl. GST) | -₹27.94 |',
        '| GST on Razorpay fees | -₹5.04 |',
        '| Refunds | -₹399.00 |',
        '| **Net of fees and refunds** | **₹965.02** |',
        '| Other costs (costs.csv) | -₹999.00 |',
        '| **Net after costs** | **-₹33.98** |',
        '',
        '### By product',
        '',
        '| Product | Payments | Gross | Fees | GST on fees | Refunds | Net |',
        '| --- | ---: | ---: | ---: | ---: | ---: | ---: |',
        '| bundle | 1 | ₹399.00 | ₹7.98 | ₹1.44 | ₹399.00 | -₹9.42 |',
        '| commission-ledger | 1 | ₹299.00 | ₹5.98 | ₹1.08 | ₹0.00 | ₹291.94 |',
        '| lead-tracker | 1 | ₹199.00 | ₹3.98 | ₹0.72 | ₹0.00 | ₹194.30 |',
        '| unmatched | 1 | ₹500.00 | ₹10.00 | ₹1.80 | ₹0.00 | ₹488.20 |',
        '',
        '### Costs',
        '',
        '| Date | Service | Amount | Note |',
        '| --- | --- | ---: | --- |',
        '| 2026-10-06 | domain | ₹999.00 | renewal \\| 1 yr |',
        '',
      ].join('\n'),
    );
  });

  it('uses lakh grouping for large weeks', () => {
    const big = computeWeeklyPnl({
      week: '2026-W41',
      sales: Array.from({ length: 620 }, (_, i) => sale(`pay_${String(i)}`, 'bundle', 19900, 0, 0)),
      refunds: [],
      costs: [],
    });
    // 620 × ₹199 = ₹1,23,380.00
    expect(renderWeeklyPnl(big)).toContain('| Gross sales (620 payments) | ₹1,23,380.00 |');
  });

  it('attributes a refund of an unknown payment to "unmatched" and handles an empty week', () => {
    const p = computeWeeklyPnl({
      week: '2026-W53',
      sales: [],
      refunds: [refund('rfnd_X', 'pay_GONE', 500, '2027-01-03')],
      costs: [],
    });
    expect(p.byProduct).toEqual([
      {
        product: 'unmatched',
        count: 0,
        grossPaise: 0,
        feesPaise: 0,
        taxOnFeesPaise: 0,
        refundsPaise: 500,
        netPaise: -500,
      },
    ]);
    const empty = renderWeeklyPnl(
      computeWeeklyPnl({ week: '2026-W53', sales: [], refunds: [], costs: [] }),
    );
    expect(empty).toContain('No sales or refunds this week.');
    expect(empty).toContain('No cost lines this week.');
    expect(empty).toContain('2026-12-28 to 2027-01-03');
  });

  it('sorts cost lines by date then service', () => {
    const p = computeWeeklyPnl({
      week: '2026-W41',
      sales: [],
      refunds: [],
      costs: [
        { date: '2026-10-07', service: 'b', amountPaise: 1, note: '' },
        { date: '2026-10-06', service: 'z', amountPaise: 1, note: '' },
        { date: '2026-10-07', service: 'a', amountPaise: 1, note: '' },
      ],
    });
    expect(p.costs.map((c) => c.service)).toEqual(['z', 'a', 'b']);
  });
});

describe('upsertPnlSection', () => {
  it('creates the weekly report when missing', () => {
    expect(upsertPnlSection(null, 'P&L\n', '2026-W41')).toBe(
      `# Week 2026-W41\n\n${PNL_START}\nP&L\n${PNL_END}\n`,
    );
  });

  it('appends after an Orchestrator summary and replaces in place on re-run', () => {
    const summary = '# Week 2026-W41\n\nOrchestrator summary.\n';
    const first = upsertPnlSection(summary, 'old\n', '2026-W41');
    expect(first).toBe(
      `# Week 2026-W41\n\nOrchestrator summary.\n\n${PNL_START}\nold\n${PNL_END}\n`,
    );
    const withTail = `${first}\nMore notes.\n`;
    expect(upsertPnlSection(withTail, 'new\n', '2026-W41')).toBe(
      `# Week 2026-W41\n\nOrchestrator summary.\n\n${PNL_START}\nnew\n${PNL_END}\n\nMore notes.\n`,
    );
    expect(upsertPnlSection(first, 'old\n', '2026-W41')).toBe(first);
  });
});
