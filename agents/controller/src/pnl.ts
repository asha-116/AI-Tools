/**
 * Weekly P&L (PROCEDURE step 5) for an ISO week, from the ledger rows. Weeks run Monday–Sunday
 * on IST dates. Sales count in the week they were captured; refunds in the week they were made
 * (attributed to the product of the original sale).
 */

import {
  CAPTURED_STATUSES,
  UNMATCHED_PRODUCT,
  type CostRow,
  type RefundRow,
  type SaleRow,
} from './ledger.js';
import { formatInr } from './money.js';
import { isoWeekRange } from './time.js';

export interface ProductLine {
  product: string;
  count: number;
  grossPaise: number;
  feesPaise: number;
  taxOnFeesPaise: number;
  refundsPaise: number;
  netPaise: number;
}

export interface WeeklyPnl {
  week: string;
  startDate: string;
  endDate: string;
  total: ProductLine;
  byProduct: ProductLine[];
  costs: CostRow[];
  costsPaise: number;
  netAfterCostsPaise: number;
}

const emptyLine = (product: string): ProductLine => ({
  product,
  count: 0,
  grossPaise: 0,
  feesPaise: 0,
  taxOnFeesPaise: 0,
  refundsPaise: 0,
  netPaise: 0,
});

export function computeWeeklyPnl(input: {
  week: string;
  sales: readonly SaleRow[];
  refunds: readonly RefundRow[];
  costs: readonly CostRow[];
}): WeeklyPnl {
  const { week, startDate, endDate } = isoWeekRange(input.week);
  const inWeek = (d: string) => d >= startDate && d <= endDate;
  const lines = new Map<string, ProductLine>();
  const line = (p: string) => {
    let l = lines.get(p);
    if (!l) {
      l = emptyLine(p);
      lines.set(p, l);
    }
    return l;
  };
  const productOf = new Map(input.sales.map((s) => [s.paymentId, s.productSlug]));

  for (const s of input.sales) {
    if (!inWeek(s.date) || !CAPTURED_STATUSES.has(s.status)) continue;
    const l = line(s.productSlug);
    l.count += 1;
    l.grossPaise += s.amountPaise;
    l.feesPaise += s.feePaise;
    l.taxOnFeesPaise += s.taxOnFeePaise;
  }
  for (const r of input.refunds) {
    if (!inWeek(r.date)) continue;
    line(productOf.get(r.paymentId) ?? UNMATCHED_PRODUCT).refundsPaise += r.amountPaise;
  }
  const byProduct = [...lines.values()]
    .map((l) => ({
      ...l,
      netPaise: l.grossPaise - l.feesPaise - l.taxOnFeesPaise - l.refundsPaise,
    }))
    .sort((a, b) => (a.product < b.product ? -1 : 1));
  const total = byProduct.reduce(
    (t, l) => ({
      product: t.product,
      count: t.count + l.count,
      grossPaise: t.grossPaise + l.grossPaise,
      feesPaise: t.feesPaise + l.feesPaise,
      taxOnFeesPaise: t.taxOnFeesPaise + l.taxOnFeesPaise,
      refundsPaise: t.refundsPaise + l.refundsPaise,
      netPaise: t.netPaise + l.netPaise,
    }),
    emptyLine('Total'),
  );
  const costs = input.costs
    .filter((c) => inWeek(c.date))
    .sort((a, b) =>
      a.date === b.date ? (a.service < b.service ? -1 : 1) : a.date < b.date ? -1 : 1,
    );
  const costsPaise = costs.reduce((a, c) => a + c.amountPaise, 0);
  return {
    week,
    startDate,
    endDate,
    total,
    byProduct,
    costs,
    costsPaise,
    netAfterCostsPaise: total.netPaise - costsPaise,
  };
}

/** Markdown cells must not break the table. */
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/[\r\n]+/g, ' ');

export function renderWeeklyPnl(p: WeeklyPnl): string {
  const t = p.total;
  const lines = [
    `## Weekly P&L — ${p.week}`,
    '',
    `${p.startDate} to ${p.endDate} (Monday–Sunday, IST). Generated by the Controller from`,
    '`company/ledger/*.csv`. Arithmetic only — not tax advice; GST treatment is for a CA to confirm.',
    '',
    '| Line | Amount |',
    '| --- | ---: |',
    `| Gross sales (${String(t.count)} payments) | ${formatInr(t.grossPaise)} |`,
    `| Razorpay fees (excl. GST) | ${formatInr(-t.feesPaise)} |`,
    `| GST on Razorpay fees | ${formatInr(-t.taxOnFeesPaise)} |`,
    `| Refunds | ${formatInr(-t.refundsPaise)} |`,
    `| **Net of fees and refunds** | **${formatInr(t.netPaise)}** |`,
    `| Other costs (costs.csv) | ${formatInr(-p.costsPaise)} |`,
    `| **Net after costs** | **${formatInr(p.netAfterCostsPaise)}** |`,
    '',
    '### By product',
    '',
  ];
  if (p.byProduct.length === 0) {
    lines.push('No sales or refunds this week.');
  } else {
    lines.push(
      '| Product | Payments | Gross | Fees | GST on fees | Refunds | Net |',
      '| --- | ---: | ---: | ---: | ---: | ---: | ---: |',
      ...p.byProduct.map(
        (l) =>
          `| ${cell(l.product)} | ${String(l.count)} | ${formatInr(l.grossPaise)} | ` +
          `${formatInr(l.feesPaise)} | ${formatInr(l.taxOnFeesPaise)} | ` +
          `${formatInr(l.refundsPaise)} | ${formatInr(l.netPaise)} |`,
      ),
    );
  }
  lines.push('', '### Costs', '');
  if (p.costs.length === 0) {
    lines.push('No cost lines this week.');
  } else {
    lines.push(
      '| Date | Service | Amount | Note |',
      '| --- | --- | ---: | --- |',
      ...p.costs.map(
        (c) => `| ${c.date} | ${cell(c.service)} | ${formatInr(c.amountPaise)} | ${cell(c.note)} |`,
      ),
    );
  }
  return lines.join('\n') + '\n';
}

export const PNL_START = '<!-- controller:pnl:start -->';
export const PNL_END = '<!-- controller:pnl:end -->';

/**
 * company/reports/weekly/<week>.md is shared with the Orchestrator's summary, so the P&L lives
 * between markers: replaced in place if present, appended otherwise.
 */
export function upsertPnlSection(existing: string | null, section: string, week: string): string {
  const block = `${PNL_START}\n${section}${PNL_END}\n`;
  if (existing === null || existing.trim() === '') return `# Week ${week}\n\n${block}`;
  const start = existing.indexOf(PNL_START);
  const end = existing.indexOf(PNL_END);
  if (start !== -1 && end > start) {
    const after = existing.slice(end + PNL_END.length).replace(/^\n/, '');
    return existing.slice(0, start) + block + after;
  }
  return `${existing.replace(/\n*$/, '\n\n')}${block}`;
}
